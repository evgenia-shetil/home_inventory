// Довші слова перевіряємо першими: «крем для обличчя» має перемогти
// «крем для тіла», а не програти йому через порядок у словнику.
const FLAT = RULES
  .flatMap(rule => rule.words.map(word => ({ ...rule, word })))
  .sort((a, b) => b.word.length - a.word.length)

export function suggestCategory(name, categories = []) {
  const empty = { rootId: null, childId: null }
  const haystack = (name ?? '').toLowerCase()
  if (!haystack) return empty

  const hit = FLAT.find(rule => haystack.includes(rule.word))
  if (!hit) return empty

  const root = categories.find(c => !c.parent_id && c.name === hit.root)
  if (!root) return empty

  const child = categories.find(c => c.parent_id === root.id && c.name === hit.child)

  return { rootId: root.id, childId: child?.id ?? null }
}
