import { describe, it, expect } from 'vitest'
import { plural } from './plural.js'

const марка = n => plural(n, 'марка', 'марки', 'марок')

describe('plural', () => {
  it('одна', () => {
    expect(марка(1)).toBe('марка')
    expect(марка(21)).toBe('марка')
    expect(марка(101)).toBe('марка')
  })

  it('дві-чотири', () => {
    expect(марка(2)).toBe('марки')
    expect(марка(3)).toBe('марки')
    expect(марка(4)).toBe('марки')
    expect(марка(22)).toBe('марки')
  })

  it('пʼять і більше', () => {
    expect(марка(5)).toBe('марок')
    expect(марка(10)).toBe('марок')
    expect(марка(0)).toBe('марок')
  })

  // Підступ української: 11-14 беруть форму «багато», попри останню цифру
  it('одинадцять-чотирнадцять — виняток', () => {
    expect(марка(11)).toBe('марок')
    expect(марка(12)).toBe('марок')
    expect(марка(13)).toBe('марок')
    expect(марка(14)).toBe('марок')
  })

  it('сто одинадцять теж виняток', () => {
    expect(марка(111)).toBe('марок')
  })
})
